--changeset iam:008-login-history
CREATE TABLE IF NOT EXISTS login_history
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    username VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
    ip_address VARCHAR(50) NOT NULL,
    user_agent VARCHAR(500),
    device VARCHAR(100),
    location VARCHAR(150),
    threat_assessment VARCHAR(255) DEFAULT 'Normal',
    is_suspicious BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_login_history_username ON login_history(username);
CREATE INDEX IF NOT EXISTS idx_login_history_created_at ON login_history(created_at DESC);

--changeset iam:009-audit-logs
CREATE TABLE IF NOT EXISTS audit_logs
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    action VARCHAR(50) NOT NULL,
    actor VARCHAR(150) NOT NULL,
    target VARCHAR(255) NOT NULL,
    details TEXT,
    client_ip VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_action ON audit_logs(action);
CREATE INDEX IF NOT EXISTS idx_audit_logs_actor ON audit_logs(actor);
CREATE INDEX IF NOT EXISTS idx_audit_logs_target ON audit_logs(target);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs(created_at DESC);

--changeset iam:010-user-sessions
CREATE TABLE IF NOT EXISTS user_sessions
(
    id VARCHAR(100) PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    device VARCHAR(100),
    browser VARCHAR(150),
    ip_address VARCHAR(50),
    location VARCHAR(150),
    is_current BOOLEAN DEFAULT FALSE,
    last_active VARCHAR(50) DEFAULT 'Active now',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_user_sessions_username ON user_sessions(username);

--changeset iam:011-system-config
CREATE TABLE IF NOT EXISTS system_config
(
    key VARCHAR(100) PRIMARY KEY,
    value VARCHAR(500) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

